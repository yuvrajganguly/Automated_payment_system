def xlsx(name: str, rows=None, *, ztp=None) -> bytes:
    """One Vendor_data file with the four sheets Shadowfax sends."""
    import pandas as pd

    rows = FILES[name] if rows is None else rows
    vd = pd.DataFrame(rows, columns=COLUMNS)
    vd["order_date"] = pd.to_datetime(vd["order_date"])
    buf = io.BytesIO()
    with pd.ExcelWriter(buf) as xw:
        vd.to_excel(xw, sheet_name="Vendor_data", index=False)
        vd.groupby(["rider_id", "order_date"], as_index=False)["Total_orders"].sum().to_excel(
            xw, sheet_name="Rider_level", index=False
        )
        pd.DataFrame(columns=["awb_number"]).to_excel(xw, sheet_name="Large shipment", index=False)
        pd.DataFrame(
            ztp or [],
            columns=[
                "rider_id",
                "parent_id",
                "awb_number",
                "fraud_type",
                "total_penalty_amount",
                "created_date",
            ],
        ).to_excel(xw, sheet_name="ZTP Deductions", index=False)
    return buf.getvalue()


def all_files() -> list[tuple[str, bytes]]:
    return [(n, xlsx(n)) for n in FILES]
